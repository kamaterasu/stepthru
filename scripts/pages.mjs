// Writes playground/<slug>/index.html for every entry in playground/pages.json. Run with `npm run pages`.
// To add an algorithm page: add its example and figure (playground/figures.ts), add an entry to pages.json, run this.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SITE = "https://kamaterasu.github.io/stepthru/";
const ROOT = new URL("../playground/", import.meta.url);

const ENTITIES = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
const e = (text) => String(text).replace(/[&<>"']/g, (c) => ENTITIES[c]);

export const readPages = () => JSON.parse(readFileSync(new URL("pages.json", ROOT), "utf8"));

/** The HTML of one page. `prev` and `next` are its neighbors in pages.json, or undefined. */
export function pageHTML(page, prev, next) {
  const { slug, title, group, description, lead, steps, facts, hooks } = page;
  const url = `${SITE}${slug}/`;
  const ld = {
    "@context": "https://schema.org",
    "@type": "TechArticle",
    headline: `${title}, step by step`,
    description,
    url,
    about: title,
    isPartOf: { "@type": "WebSite", name: "stepthru", url: SITE },
  };
  const pager = (prev ? `<a href="../${prev.slug}/" rel="prev">← ${e(prev.title)}</a>` : "<span></span>")
    + (next ? `<a href="../${next.slug}/" rel="next">${e(next.title)} →</a>` : '<a href="../#examples">All examples →</a>');
  const hookList = hooks.map((h) => `<code>${e(h)}</code>`).join(" and ");
  return `<!doctype html>
<!-- Generated by scripts/pages.mjs from playground/pages.json. Edit those, then run npm run pages. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${e(title)} visualized step by step | stepthru</title>
    <meta name="description" content="${e(description)}" />
    <link rel="canonical" href="${url}" />
    <link rel="icon" type="image/svg+xml" href="../../brand/logo.svg" />
    <meta property="og:type" content="article" />
    <meta property="og:title" content="${e(title)}, step by step" />
    <meta property="og:description" content="${e(description)}" />
    <meta property="og:url" content="${url}" />
    <meta property="og:image" content="https://raw.githubusercontent.com/kamaterasu/stepthru/main/brand/social.png" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="theme-color" content="#ffffff" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#13121a" media="(prefers-color-scheme: dark)" />
    <link rel="stylesheet" href="../site.css" />
    <script type="application/ld+json">${JSON.stringify(ld)}</script>
  </head>
  <body data-figure="${slug}">
    <div class="layout single">
      <main>
        <p class="crumbs"><a href="../">stepthru</a> › <a href="../#example-${group.toLowerCase()}">${e(group)}</a> › ${e(title)}</p>
        <h1>${e(title)}, step by step</h1>
        <p class="lead">${e(lead)}</p>
        <div id="figure"></div>
        <p>Click the figure, then use ← →, space, Home and End, or the buttons.</p>

        <h2>How it works</h2>
        <ol>
${steps.map((s) => `          <li>${e(s)}</li>`).join("\n")}
        </ol>

        <h2>Cost</h2>
        <dl class="facts">
${facts.map(([k, v]) => `          <dt>${e(k)}</dt><dd>${e(v)}</dd>`).join("\n")}
        </dl>

        <h2>The code behind this figure</h2>
        <p>Nothing here is hand-animated. The figure comes from this code: a plain ${e(title.toLowerCase())} with <a href="../">stepthru</a> tracer calls, such as ${hookList}, that record each step.</p>
        <pre><code id="source"></code></pre>

        <h2>Make your own</h2>
        <pre><code>npm install stepthru</code></pre>
        <p>Write the algorithm once, call the tracer hooks inside it, and get a figure like this one for your own post or course. <a href="../#guide">Read the guide</a>.</p>

        <nav class="pager" aria-label="More algorithms">${pager}</nav>
      </main>
    </div>
    <script type="module" src="../algorithm.ts"></script>
  </body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pages = readPages();
  pages.forEach((page, i) => {
    const dir = new URL(`${page.slug}/`, ROOT);
    mkdirSync(dir, { recursive: true });
    writeFileSync(new URL("index.html", dir), pageHTML(page, pages[i - 1], pages[i + 1]));
  });
  console.log(`wrote ${pages.length} pages`);
}
